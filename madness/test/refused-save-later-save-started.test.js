/* A setting is switched off (save 1), on (save 2) and off again (save 3): save 3 starts from a screen that reads
 * exactly as it did for save 1. Save 1 is then refused. It took "nothing has moved since I started" from that same
 * text and put the starting point back to its own (setting on), although save 3 is on its way with "off". The next
 * tap, on again, was then "nothing changed", and save 3 landed last. */
test('a refused save does not take back the starting point when a later save has started from the same screen', withTimers(async () => {
  const { app, finish, refuse, fire, deliver, now, set, server, txs } = stampedRoom();
  set('ub', false);
  await fire();                                     // save 1: off
  set('ub', true);
  await fire();                                     // save 2: on
  set('ub', false);
  await fire();                                     // save 3: off again (the same screen as save 1)
  await refuse(0);                                  // save 1 is refused
  set('ub', true);                                  // the last tap: on
  for (let round = 0; round < 4; round++) {
    await fire();
    for (let i = 1; i < txs.length; i++) if (!txs[i].failed) await finish(i);
    deliver(now());
  }
  assert.equal(server().ub, true, 'the last choice on this phone reached the room');
  assert.equal(app.S.ub, true, 'and it stays on this screen');
}));

test('a refused save with no later save still goes back to its own starting point and is sent again', withTimers(async () => {
  const { app, finish, refuse, fire, deliver, now, set, server, txs } = stampedRoom();
  set('ub', false);
  await fire();
  await refuse(0);
  for (let round = 0; round < 3; round++) {
    await fire();
    for (let i = 1; i < txs.length; i++) if (!txs[i].failed) await finish(i);
    deliver(now());
  }
  assert.equal(server().ub, false);
  assert.equal(app.S.ub, false);
}));
